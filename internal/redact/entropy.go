package redact

import "math"

// shannon returns the Shannon entropy of s in bits per byte. It is only run on
// candidate values, never on the whole input, so the cost is negligible.
func shannon(s string) float64 {
	if len(s) == 0 {
		return 0
	}
	var counts [256]int
	for i := 0; i < len(s); i++ {
		counts[s[i]]++
	}
	var h float64
	n := float64(len(s))
	for _, c := range counts {
		if c == 0 {
			continue
		}
		p := float64(c) / n
		h -= p * math.Log2(p)
	}
	return h
}
