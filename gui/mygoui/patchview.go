package mygoui

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/egoist/mygo/ui"
)

const maxRenderedPatchLines = 1000

type patchLineKind uint8

const (
	patchContext patchLineKind = iota
	patchAdd
	patchDelete
	patchHunk
	patchMeta
)

type patchViewLine struct {
	kind patchLineKind
	text string
}

type patchViewFile struct {
	action string
	path   string
	lines  []patchViewLine
}

func applyPatchInput(input map[string]any) string {
	for _, key := range []string{"patch", "input"} {
		if value, ok := input[key].(string); ok && strings.TrimSpace(value) != "" {
			return value
		}
	}
	return ""
}

func parseApplyPatch(raw string) []patchViewFile {
	files, _ := parseApplyPatchView(raw)
	return files
}

// parseApplyPatchView also reports whether the bounded preview omitted any
// patch lines or files, so the result diff can remain available in that case.
func parseApplyPatchView(raw string) ([]patchViewFile, bool) {
	var files []patchViewFile
	current := -1
	lineCount := 0
	truncated := false
	start := func(action, path string) {
		if lineCount >= maxRenderedPatchLines {
			truncated = true
			return
		}
		path = strings.TrimSpace(path)
		if path == "" {
			path = "Unknown file"
		}
		files = append(files, patchViewFile{action: action, path: path})
		current = len(files) - 1
	}
	lines := strings.Split(strings.ReplaceAll(raw, "\r\n", "\n"), "\n")
	for i, line := range lines {
		switch {
		case strings.HasPrefix(line, "*** Update File:"):
			start("Modified", strings.TrimPrefix(line, "*** Update File:"))
			continue
		case strings.HasPrefix(line, "*** Add File:"):
			start("Added", strings.TrimPrefix(line, "*** Add File:"))
			continue
		case strings.HasPrefix(line, "*** Delete File:"):
			start("Deleted", strings.TrimPrefix(line, "*** Delete File:"))
			continue
		case line == "*** Begin Patch" || line == "*** End Patch":
			continue
		}
		if current < 0 {
			if strings.TrimSpace(line) == "" {
				continue
			}
			start("Patch", "Patch")
		}
		if lineCount >= maxRenderedPatchLines {
			if line != "" || i < len(lines)-1 {
				truncated = true
			}
			continue
		}
		viewLine := patchViewLine{kind: patchContext, text: line}
		switch {
		case strings.HasPrefix(line, "@@"):
			viewLine.kind = patchHunk
		case strings.HasPrefix(line, "***"):
			viewLine.kind = patchMeta
		case strings.HasPrefix(line, "+"):
			viewLine.kind, viewLine.text = patchAdd, strings.TrimPrefix(line, "+")
		case strings.HasPrefix(line, "-"):
			viewLine.kind, viewLine.text = patchDelete, strings.TrimPrefix(line, "-")
		case strings.HasPrefix(line, " "):
			viewLine.text = strings.TrimPrefix(line, " ")
		}
		files[current].lines = append(files[current].lines, viewLine)
		lineCount++
	}
	return files, truncated
}

func applyPatchSubject(input map[string]any) string {
	files := parseApplyPatch(applyPatchInput(input))
	switch len(files) {
	case 0:
		return "patch"
	case 1:
		return files[0].path
	default:
		return fmt.Sprintf("%d files", len(files))
	}
}

// applyPatchDisplayOutput keeps the result summary and any diagnostics without
// repeating a unified diff already represented by the patch preview. Details
// are present for live calls, while older replayed results may only have text.
func applyPatchDisplayOutput(output string, details map[string]any) string {
	first, _, ok := strings.Cut(output, "\n")
	if !ok || !strings.HasPrefix(first, "Applied ") || !strings.HasSuffix(first, " change(s):") {
		return output
	}
	count := strings.TrimSuffix(strings.TrimPrefix(first, "Applied "), " change(s):")
	if n, err := strconv.Atoi(count); err != nil || n <= 0 {
		return output
	}
	if diff, ok := details["diff"].(string); ok && strings.HasPrefix(diff, "--- a/") {
		if i := strings.LastIndex(output, diff); i > len(first) && output[i-1] == '\n' {
			return output[:i-1] + output[i+len(diff):]
		}
	}
	// History can omit Details, and redaction can make its diff differ from the
	// displayed result. Only recognize the tool's own unified-diff shape and
	// count hunk lines so a later note or truncation notice stays visible.
	i := strings.Index(output, "\n--- a/")
	if i < 0 {
		return output
	}
	diff := output[i+1:]
	pos, ok := appliedDiffEnd(diff)
	if !ok {
		return output
	}
	tail := diff[pos:]
	if tail != "" && !strings.HasPrefix(tail, "\n") {
		tail = "\n" + tail
	}
	return output[:i] + tail
}

// appliedDiffEnd parses the output generated by unifiedDiffLimited. Hunk line
// counts distinguish context lines from a diagnostic that begins with spaces,
// '+' or '-'. A malformed diff is left untouched rather than hiding output.
func appliedDiffEnd(diff string) (int, bool) {
	lineAt := func(pos int) (string, int) {
		line, _, found := strings.Cut(diff[pos:], "\n")
		next := pos + len(line)
		if found {
			next++
		}
		return line, next
	}
	pos := 0
	files := 0
	for pos < len(diff) {
		line, next := lineAt(pos)
		if !strings.HasPrefix(line, "--- a/") {
			break
		}
		if next >= len(diff) {
			return 0, false
		}
		line, next = lineAt(next)
		if !strings.HasPrefix(line, "+++ b/") || next >= len(diff) {
			return 0, false
		}
		pos = next
		hunks := 0
		for pos < len(diff) {
			line, next = lineAt(pos)
			if !strings.HasPrefix(line, "@@ ") {
				break
			}
			var oldStart, oldCount, newStart, newCount int
			if n, err := fmt.Sscanf(line, "@@ -%d,%d +%d,%d @@", &oldStart, &oldCount, &newStart, &newCount); err != nil || n != 4 || oldCount < 0 || newCount < 0 || oldCount+newCount == 0 {
				return 0, false
			}
			pos = next
			for oldCount > 0 || newCount > 0 {
				if pos >= len(diff) {
					return 0, false
				}
				line, next = lineAt(pos)
				if strings.HasPrefix(line, "... (diff truncated;") {
					return pos, true
				}
				switch {
				case strings.HasPrefix(line, " "):
					oldCount--
					newCount--
				case strings.HasPrefix(line, "-"):
					oldCount--
				case strings.HasPrefix(line, "+"):
					newCount--
				default:
					return 0, false
				}
				if oldCount < 0 || newCount < 0 {
					return 0, false
				}
				pos = next
			}
			hunks++
		}
		if hunks == 0 {
			return 0, false
		}
		files++
	}
	return pos, files > 0
}

func renderApplyPatch(c *ui.Context, input map[string]any) (rendered, complete bool) {
	files, truncated := parseApplyPatchView(applyPatchInput(input))
	if len(files) == 0 {
		return false, false
	}
	// Delete operations contain only a path in the patch input; their removed
	// contents exist only in the result diff, so that diff is not redundant.
	hasDeletion := false
	for _, file := range files {
		if file.action == "Deleted" {
			hasDeletion = true
			break
		}
	}
	t := c.Theme()
	ui.Column(c).MarginStart(18).Gap(8).Children(func() {
		for fileIndex, file := range files {
			file := file
			ui.Column(c.Key(fmt.Sprintf("patch-file:%d:%s", fileIndex, file.path))).Radius(8).Border(1, t.Border).Clip().Children(func() {
				ui.Row(c).Padding(6, 10).Gap(8).AlignItems(ui.Center).Background(t.SurfacePressed).Children(func() {
					ui.Text(c, file.path).FontSize(12).FontWeight(600).TextColor(t.Text).Grow(1).SingleLine().Ellipsis("…").Tooltip(file.path)
					ui.Text(c, file.action).FontSize(10.5).TextColor(t.TextMuted)
				})
				for lineIndex, line := range file.lines {
					line := line
					row := ui.Row(c.Key(fmt.Sprintf("patch-line:%d:%d", fileIndex, lineIndex))).Padding(2, 8).Gap(6).AlignItems(ui.Start)
					marker, markerColor, textColor := " ", t.TextMuted, t.Text
					switch line.kind {
					case patchAdd:
						marker, markerColor = "+", t.Success
						row.Background(t.Success.Alpha(.10))
					case patchDelete:
						marker, markerColor = "−", t.Danger
						row.Background(t.Danger.Alpha(.08))
					case patchHunk:
						marker, textColor = "@@", t.TextMuted
						row.Background(t.Surface)
					case patchMeta:
						marker, textColor = "·", t.TextMuted
					}
					row.Children(func() {
						ui.Text(c, marker).Width(22).Font("monospace").FontSize(11).TextColor(markerColor).TextAlign(ui.Center)
						text := line.text
						if text == "" {
							text = " "
						}
						ui.Text(c, text).Grow(1).Font("monospace").FontSize(11.5).TextColor(textColor).Selectable().Wrap()
					})
				}
			})
		}
		if truncated {
			ui.Text(c, "Patch preview truncated; the tool result is shown below.").FontSize(11).TextColor(t.TextMuted)
		} else if hasDeletion {
			ui.Text(c, "Deleted file contents are shown in the tool result below.").FontSize(11).TextColor(t.TextMuted)
		}
	})
	return true, !truncated && !hasDeletion
}
